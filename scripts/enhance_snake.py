#!/usr/bin/env python3
"""Give a Platane/snk SVG an animated, neon-premium presentation frame.

The input is generated by Platane/snk and contains real contributions and animation.
The script nests that original SVG intact in a decorated outer SVG so the
contribution cells, snake path and original animations remain dynamic.
Requires only Python's standard library.
"""
from __future__ import annotations
import argparse
import datetime as dt
import html
from pathlib import Path
import re
import xml.etree.ElementTree as ET

SVG_NS = 'http://www.w3.org/2000/svg'
XLINK_NS = 'http://www.w3.org/1999/xlink'
ET.register_namespace('', SVG_NS)
ET.register_namespace('xlink', XLINK_NS)


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def render(input_file: Path, output_file: Path, theme: str, username: str) -> None:
    if input_file.resolve() == output_file.resolve():
        raise ValueError('Input and output must be different files')
    original = ET.parse(input_file).getroot()
    if original.tag not in (f'{{{SVG_NS}}}svg', 'svg'):
        raise ValueError('The supplied file is not an SVG')
    if 'viewBox' not in original.attrib:
        w = re.sub(r'[^\d.]', '', original.attrib.get('width', '880'))
        h = re.sub(r'[^\d.]', '', original.attrib.get('height', '192'))
        original.set('viewBox', f'0 0 {w} {h}')
    original.set('x', '42')
    original.set('y', '90')
    original.set('width', '1116')
    original.set('height', '256')
    original.set('preserveAspectRatio', 'xMidYMid meet')

    year = dt.datetime.now(dt.timezone.utc).year
    name = re.sub(r'[^a-zA-Z0-9-]', '', username)[:39] or 'GITHUB'
    if theme == 'dark':
        colors = dict(bg1='#060917', bg2='#111B35', bg3='#051E30', frame='#265A71',
                      title='#EDF8FF', text='#A8BCD4', muted='#7496AA', cyan='#6EFCE0',
                      blue='#63A7FF', orchid='#AB85FF', glow='#38E7D6', line='#5BA3B8',
                      pill='#0B2033', grid0='#122A38', grid1='#165C68', grid2='#207E81',
                      grid3='#35B8A8', grid4='#A8FFD6')
    else:
        colors = dict(bg1='#F1FAFF', bg2='#E9EFFC', bg3='#DEF8F4', frame='#7FB8CD',
                      title='#16304D', text='#436881', muted='#527A93', cyan='#028B81',
                      blue='#2862B4', orchid='#6947AA', glow='#20AAB1', line='#83B7C7',
                      pill='#E4F7F6', grid0='#E1F0F1', grid1='#B5E0DE', grid2='#70C5BB',
                      grid3='#32AFA0', grid4='#137C78')
    c=colors
    sparkles = []
    for i in range(33):
        x = 23+(i * 107 + (i*i*19)) % 1157
        y = 17+(i * 31 + (i*i*7)) % 360
        if 92<y<332: continue
        r=0.75 if i % 3 else 1.5
        op=0.22 if i%4 else 0.5
        sparkles.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{c["cyan"]}" opacity="{op}"/>')
    sparkles_string=''.join(sparkles)

    # Put the original SVG INSIDE this SVG, after the artboard, and before chrome.
    header = f'''<svg xmlns="{SVG_NS}" width="1200" height="400" viewBox="0 0 1200 400" role="img" aria-labelledby="title desc">
<title id="title">{esc(name)} — live contribution snake</title>
<desc id="desc">Automatic contribution animation generated from real GitHub activity with a neon premium background.</desc>
<defs>
  <linearGradient id="pbg" x1="0" y1="0" x2="1" y2="1">
    <stop stop-color="{c['bg1']}"/><stop offset=".52" stop-color="{c['bg2']}"/><stop offset="1" stop-color="{c['bg3']}"/>
  </linearGradient>
  <linearGradient id="pstroke" x1="0" y1="0" x2="1" y2="0"><stop stop-color="{c['orchid']}" stop-opacity=".4"/><stop offset=".55" stop-color="{c['cyan']}" stop-opacity=".8"/><stop offset="1" stop-color="{c['blue']}" stop-opacity=".2"/></linearGradient>
  <linearGradient id="ptext" x1="0" y1="0" x2="1" y2="0"><stop stop-color="{c['cyan']}"/><stop offset="1" stop-color="{c['blue']}"/></linearGradient>
  <linearGradient id="psnake" x1="0" y1="0" x2="1" y2="1"><stop stop-color="{c['cyan']}"/><stop offset=".6" stop-color="{c['glow']}"/><stop offset="1" stop-color="{c['blue']}"/></linearGradient>
  <radialGradient id="porb1"><stop stop-color="{c['orchid']}" stop-opacity=".22"/><stop offset="1" stop-color="{c['orchid']}" stop-opacity="0"/></radialGradient>
  <radialGradient id="porb2"><stop stop-color="{c['cyan']}" stop-opacity=".16"/><stop offset="1" stop-color="{c['cyan']}" stop-opacity="0"/></radialGradient>
  <clipPath id="pcard"><rect x="7" y="7" width="1186" height="386" rx="27"/></clipPath>
</defs>
<g clip-path="url(#pcard)">
  <rect x="7" y="7" width="1186" height="386" rx="27" fill="url(#pbg)"/>
  <circle cx="1039" cy="32" r="328" fill="url(#porb1)"/>
  <circle cx="70" cy="355" r="285" fill="url(#porb2)"/>
  <path d="M 694 -82 Q 941 158 1284 176" fill="none" stroke="{c['orchid']}" stroke-width="1.2" stroke-opacity=".16"/>
  <path d="M 770 -78 Q 985 123 1266 132" fill="none" stroke="{c['cyan']}" stroke-width="1.2" stroke-opacity=".16"/>
  <path d="M -30 330 Q 280 232 585 409" fill="none" stroke="{c['cyan']}" stroke-width="1.1" stroke-opacity=".1"/>
  {sparkles_string}
  <rect x="21" y="21" width="1158" height="358" rx="20" fill="none" stroke="{c['line']}" stroke-opacity=".22"/>
  <circle cx="52" cy="48" r="5" fill="{c['cyan']}"/>
  <circle cx="52" cy="48" r="9" fill="none" stroke="{c['cyan']}" opacity=".23"><animate attributeName="r" values="6;14;6" dur="3s" repeatCount="indefinite"/></circle>
  <text x="68" y="52" font-family="Arial,sans-serif" font-size="10" font-weight="700" letter-spacing="2.3" fill="{c['muted']}">GITHUB  //  LIVE CONTRIBUTIONS</text>
  <text x="47" y="87" font-family="Arial,sans-serif" font-size="27" font-weight="800" letter-spacing="1" fill="{c['title']}">CONTRIBUTION <tspan fill="url(#ptext)">UNIVERSE</tspan></text>
  <rect x="938" y="37" width="220" height="29" rx="14.5" fill="{c['pill']}" stroke="{c['cyan']}" stroke-opacity=".23"/>
  <circle cx="955" cy="52" r="3.5" fill="{c['cyan']}"/>
  <text x="970" y="56" font-family="Arial,sans-serif" font-size="10.5" letter-spacing="1" font-weight="700" fill="{c['title']}">AUTO-UPDATING · {year}</text>
  <line x1="39" y1="109" x2="1162" y2="109" stroke="{c['line']}" stroke-opacity=".24"/>
</g>'''
    # Re-serialize the original without discarding animation keyframes / CSS.
    inner_xml = ET.tostring(original, encoding='unicode')
    # ET causes nested xmlns declarations if its root includes namespaces, which is valid.
    # Inline the dynamic original after top chrome: its CSS animation keeps running.
    css = f'''<style>
/* The original Platane/snk animation is unchanged; visual upgrades below. */
.s {{ fill: url(#psnake) !important; filter: drop-shadow(0 0 3px {c['cyan']}) drop-shadow(0 0 6px {c['glow']}); }}
.s.s0 {{ fill: {('#FFF4A8' if theme=='dark' else '#FCDF67')} !important; filter: drop-shadow(0 0 4px {c['cyan']}) drop-shadow(0 0 8px {c['glow']}); }}
</style>'''
    footer = f'''<g clip-path="url(#pcard)">
<line x1="39" y1="350" x2="1162" y2="350" stroke="{c['line']}" stroke-opacity=".28"/>
<text x="47" y="371" font-family="Arial,sans-serif" font-size="10.5" font-weight="700" letter-spacing="1.2" fill="{c['text']}">EVERY COMMIT TELLS A STORY</text>
<text x="554" y="371" font-family="Arial,sans-serif" font-size="10.5" letter-spacing="1" fill="{c['muted']}">CODE  ·  BUILD  ·  EVOLVE</text>
<text x="951" y="371" font-family="Arial,sans-serif" font-size="10.5" letter-spacing="1.1" fill="{c['text']}">@{esc(name)}</text>
</g>
<rect x="7" y="7" width="1186" height="386" rx="27" fill="none" stroke="url(#pstroke)" stroke-width="1.4"/>
</svg>'''
    # inner snk CSS can declare keyframes without collision with wrapper.
    complete = '<?xml version="1.0" encoding="UTF-8"?>\n' + header + '\n' + inner_xml + '\n' + css + '\n' + footer
    ET.fromstring(complete)  # validate XML before writing
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(complete, encoding='utf-8')
    print(f'Enhanced {input_file} → {output_file} ({theme})')


if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--input', required=True, type=Path)
    p.add_argument('--output', required=True, type=Path)
    p.add_argument('--theme', choices=['dark','light'], default='dark')
    p.add_argument('--username', default='developer')
    a=p.parse_args()
    render(a.input,a.output,a.theme,a.username)
